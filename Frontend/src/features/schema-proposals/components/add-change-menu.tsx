import { ChevronDown, Columns3, GitFork, KeyRound, Plus, Table2, Wrench } from 'lucide-react'
import { Button } from '@/components/ui/button'
import { DropdownMenu, DropdownMenuContent, DropdownMenuItem, DropdownMenuLabel, DropdownMenuSeparator, DropdownMenuTrigger } from '@/components/ui/dropdown-menu'
import type { NewChangeKind } from '../lib/form'

const TABLE_ITEMS: { kind: NewChangeKind; label: string; hint: string }[] = [
  { kind: 'fact', label: 'Create fact table', hint: 'Events at a fixed grain with measures' },
  { kind: 'dimension', label: 'Create dimension table', hint: 'Descriptive attributes joined from facts' },
]

const MODIFY_ITEMS: { kind: NewChangeKind; label: string; hint: string; icon: typeof Plus }[] = [
  { kind: 'add_relationship', label: 'Add relationship', hint: 'Foreign key enforced by a dbt test', icon: GitFork },
  { kind: 'add_surrogate_key', label: 'Add surrogate key', hint: 'Hash key generated by dbt_utils', icon: KeyRound },
  { kind: 'add_column', label: 'Add column', hint: 'Extend an existing model', icon: Columns3 },
  { kind: 'alter_column', label: 'Change column type', hint: 'Alter the type of a column', icon: Wrench },
]

export function AddChangeMenu({ onAdd, variant = 'outline' }: { onAdd: (kind: NewChangeKind) => void; variant?: 'outline' | 'default' }) {
  return (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button type="button" variant={variant} size="sm">
          <Plus aria-hidden />
          Add change
          <ChevronDown className="size-3.5 opacity-60" aria-hidden />
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="end" className="w-72">
        <DropdownMenuLabel>New table</DropdownMenuLabel>
        {TABLE_ITEMS.map((item) => (
          <DropdownMenuItem key={item.kind} onSelect={() => onAdd(item.kind)} className="items-start">
            <Table2 className="mt-0.5" aria-hidden />
            <span className="flex flex-col">
              <span>{item.label}</span>
              <span className="text-xs text-muted-foreground">{item.hint}</span>
            </span>
          </DropdownMenuItem>
        ))}
        <DropdownMenuSeparator />
        <DropdownMenuLabel>Modify models</DropdownMenuLabel>
        {MODIFY_ITEMS.map((item) => (
          <DropdownMenuItem key={item.kind} onSelect={() => onAdd(item.kind)} className="items-start">
            <item.icon className="mt-0.5" aria-hidden />
            <span className="flex flex-col">
              <span>{item.label}</span>
              <span className="text-xs text-muted-foreground">{item.hint}</span>
            </span>
          </DropdownMenuItem>
        ))}
      </DropdownMenuContent>
    </DropdownMenu>
  )
}
