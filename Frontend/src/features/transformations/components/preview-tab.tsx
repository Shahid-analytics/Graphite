import { ArrowUpRight, TableProperties } from 'lucide-react'
import { useState } from 'react'
import { Link } from 'react-router'
import { TimeAgo } from '@/components/data/display'
import { EmptyState, ErrorState, TableSkeleton } from '@/components/feedback/states'
import { SimulatedBadge } from '@/components/status/simulated'
import { Pagination } from '@/components/tables/data-table'
import { Button } from '@/components/ui/button'
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui/table'
import { wsPath } from '@/hooks/use-workspace'
import { formatNumber } from '@/lib/format'
import { cn } from '@/lib/utils'
import { useModelPreview } from '../queries'

const PAGE_SIZE = 25

function Cell({ value }: { value: unknown }) {
  if (value === null || value === undefined) return <span className="text-subtle-foreground italic">null</span>
  if (typeof value === 'boolean') return <span>{value ? 'true' : 'false'}</span>
  if (typeof value === 'number') return <span className="tabular">{value.toLocaleString('en-IN')}</span>
  if (typeof value === 'object') return <span>{JSON.stringify(value)}</span>
  return <span>{String(value)}</span>
}

/** Bounded sample of the model's output relation. */
export function PreviewTab({ workspaceId, modelId }: { workspaceId: string; modelId: string | null }) {
  const [page, setPage] = useState(1)
  const query = useModelPreview(modelId, { page, page_size: PAGE_SIZE })

  if (!modelId) {
    return (
      <EmptyState
        icon={TableProperties}
        title="No output relation to preview"
        description="This model does not build a warehouse relation (for example an ephemeral model), so there are no rows to sample."
      />
    )
  }
  if (query.isPending) return <TableSkeleton rows={8} columns={6} />
  if (query.isError) return <ErrorState error={query.error} title="Could not load sample rows" onRetry={() => query.refetch()} />

  const preview = query.data
  if (!preview.rows.length) {
    return (
      <EmptyState
        icon={TableProperties}
        title="The output relation is empty"
        description="Run the model to build it, then sample rows appear here."
      />
    )
  }

  const total = preview.total_rows
  return (
    <div className="space-y-3">
      <div className="flex flex-wrap items-center gap-2 text-sm">
        <span className="text-muted-foreground">
          Sample rows{total !== null ? ` from ${formatNumber(total)} total` : ''} · sampled <TimeAgo value={preview.sampled_at} />
        </span>
        <SimulatedBadge reason="Sample rows are generated by the in-browser mock API. No warehouse was queried." />
        <Button asChild variant="ghost" size="sm" className="ml-auto">
          <Link to={`${wsPath(workspaceId, 'preview')}?model=${encodeURIComponent(modelId)}`}>
            Open in Data preview
            <ArrowUpRight className="size-3.5" aria-hidden />
          </Link>
        </Button>
      </div>
      <div className={cn('rounded-lg border border-border bg-background', query.isPlaceholderData && 'opacity-70 transition-opacity')}>
        <Table containerClassName="rounded-t-lg">
          <caption className="sr-only">Sample rows</caption>
          <TableHeader>
            <TableRow className="hover:bg-transparent">
              {preview.columns.map((c) => (
                <TableHead key={c.name} className="whitespace-nowrap">
                  <span className="font-mono normal-case">{c.name}</span>
                  <span className="ml-1.5 font-mono text-[10px] font-normal normal-case text-subtle-foreground">{c.data_type}</span>
                </TableHead>
              ))}
            </TableRow>
          </TableHeader>
          <TableBody>
            {preview.rows.map((row, i) => (
              <TableRow key={i}>
                {preview.columns.map((c) => (
                  <TableCell key={c.name} className="max-w-64 truncate font-mono text-xs whitespace-nowrap">
                    <Cell value={row[c.name]} />
                  </TableCell>
                ))}
              </TableRow>
            ))}
          </TableBody>
        </Table>
        {total !== null && total > preview.page_size ? (
          <Pagination
            page={preview.page}
            totalPages={Math.max(1, Math.ceil(total / preview.page_size))}
            total={total}
            pageSize={preview.page_size}
            onPageChange={setPage}
          />
        ) : null}
      </div>
    </div>
  )
}
