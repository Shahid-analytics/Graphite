import { ExternalLink, TableProperties } from 'lucide-react'
import { Link } from 'react-router'
import { TimeAgo } from '@/components/data/display'
import { EmptyState, ErrorState, TableSkeleton } from '@/components/feedback/states'
import { SimulatedBadge } from '@/components/status/simulated'
import { Button } from '@/components/ui/button'
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '@/components/ui/table'
import { wsPath } from '@/hooks/use-workspace'
import { formatNumber } from '@/lib/format'
import { cn } from '@/lib/utils'
import type { DataModel } from '@/types'
import { useModelPreview } from '../../queries'

const PREVIEW_QUERY = { page: 1, page_size: 25 }

function Cell({ value }: { value: unknown }) {
  if (value === null || value === undefined) return <span className="text-subtle-foreground italic">null</span>
  if (typeof value === 'boolean') return <span className="text-muted-foreground">{String(value)}</span>
  if (typeof value === 'number') return <span className="tabular">{value.toLocaleString('en')}</span>
  return <>{String(value)}</>
}

export function PreviewTab({ model, workspaceId }: { model: DataModel; workspaceId: string }) {
  const query = useModelPreview(model.id, PREVIEW_QUERY)
  const fullPreview = `${wsPath(workspaceId, 'preview')}?model=${encodeURIComponent(model.id)}`

  const header = (
    <div className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
      <div className="flex flex-wrap items-center gap-2 text-xs text-muted-foreground">
        <SimulatedBadge label="Simulated rows" reason="Rows are generated by the in-browser mock API from the column definitions. They are not read from the warehouse." />
        {query.data ? (
          <span>
            First {formatNumber(query.data.rows.length)} of {formatNumber(query.data.total_rows)} sample rows, sampled <TimeAgo value={query.data.sampled_at} />
          </span>
        ) : null}
      </div>
      <Button variant="outline" size="sm" asChild>
        <Link to={fullPreview}>
          <ExternalLink aria-hidden />
          Browse in data preview
        </Link>
      </Button>
    </div>
  )

  if (query.isPending) {
    return (
      <div className="space-y-3">
        {header}
        <TableSkeleton rows={8} columns={6} />
      </div>
    )
  }
  if (query.isError) return <ErrorState error={query.error} title="Could not load sample rows" onRetry={() => query.refetch()} />

  const { columns, rows } = query.data
  return (
    <div className="space-y-3">
      {header}
      {!rows.length || !columns.length ? (
        <EmptyState
          compact
          icon={TableProperties}
          title="No rows to preview"
          description={columns.length ? 'This table is empty or has not been loaded yet.' : 'The columns of this table have not been profiled yet, so no sample can be shown.'}
        />
      ) : (
        <div className="rounded-lg border border-border bg-background">
          <Table containerClassName="scrollbar-thin max-h-[32rem] rounded-lg">
            <caption className="sr-only">Sample rows from {model.schema}.{model.name}</caption>
            <TableHeader className="sticky top-0 z-10 bg-surface">
              <TableRow className="hover:bg-transparent">
                {columns.map((c) => (
                  <TableHead key={c.name} className="whitespace-nowrap normal-case">
                    <span className="font-mono text-xs text-foreground">{c.name}</span>
                    <span className="ml-1.5 font-mono text-[11px] font-normal text-subtle-foreground">{c.data_type}</span>
                  </TableHead>
                ))}
              </TableRow>
            </TableHeader>
            <TableBody>
              {rows.map((row, i) => (
                <TableRow key={i}>
                  {columns.map((c) => (
                    <TableCell key={c.name} className={cn('max-w-64 truncate font-mono text-xs whitespace-nowrap', typeof row[c.name] === 'number' && 'text-right')}>
                      <Cell value={row[c.name]} />
                    </TableCell>
                  ))}
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </div>
      )}
    </div>
  )
}
