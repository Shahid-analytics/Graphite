import { ArrowUpRight, ChevronLeft, ChevronRight, SearchX } from 'lucide-react'
import { useState } from 'react'
import { Link } from 'react-router'
import { HelpTip, TimeAgo } from '@/components/data/display'
import { EmptyState, ErrorState, TableSkeleton } from '@/components/feedback/states'
import { LayerBadge } from '@/components/status/status-badge'
import { SimulatedBadge } from '@/components/status/simulated'
import { Pagination, SearchInput, TableToolbar } from '@/components/tables/data-table'
import { Badge } from '@/components/ui/badge'
import { Button } from '@/components/ui/button'
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select'
import { wsPath } from '@/hooks/use-workspace'
import { formatNumber } from '@/lib/format'
import type { DataModel } from '@/types'
import { useDebouncedValue } from '../lib/use-debounced-value'
import { useModelPreview } from '../queries'
import { ColumnMenu } from './column-menu'
import { PreviewGrid, type SortState } from './preview-grid'

const PAGE_SIZES = [25, 50, 100]

/** Header, toolbar and grid for one table. Mounted with `key={model.id}` so state resets per table. */
export function PreviewPanel({ model, workspaceId }: { model: DataModel; workspaceId: string }) {
  const [search, setSearch] = useState('')
  const q = useDebouncedValue(search.trim(), 300)
  // Page is tied to the filter it was chosen for, so a new filter starts at page 1 without an effect.
  const [paging, setPaging] = useState({ q: '', page: 1 })
  const page = paging.q === q ? paging.page : 1
  const [pageSize, setPageSize] = useState(25)
  const [sort, setSort] = useState<SortState | null>(null)
  const [hidden, setHidden] = useState<Set<string>>(new Set())

  const preview = useModelPreview(model.id, { page, page_size: pageSize, sort: sort?.column, order: sort?.order, q: q || undefined })
  const data = preview.data
  const columns = (data?.columns ?? []).filter((c) => !hidden.has(c.name))
  const qualified = `${model.schema}.${model.name}`

  const setPage = (next: number) => setPaging({ q, page: next })
  const toggleSort = (column: string) => {
    setSort((prev) => (prev?.column !== column ? { column, order: 'asc' } : prev.order === 'asc' ? { column, order: 'desc' } : null))
    setPage(1)
  }

  const total = data?.total_rows ?? null
  const hasNext = total === null ? (data?.rows.length ?? 0) === pageSize : page * pageSize < total

  return (
    <div className="space-y-4">
      <section aria-label="Table summary" className="flex flex-col gap-3 rounded-lg border border-border bg-background px-4 py-3 shadow-xs md:flex-row md:items-center">
        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-2">
            <h2 className="truncate font-mono text-sm font-semibold">{qualified}</h2>
            <LayerBadge layer={model.layer} />
            <Badge variant="outline">{model.role}</Badge>
            <SimulatedBadge label="Simulated rows" reason="Sample rows are generated by the in-browser mock API from the table's column definitions. No warehouse was queried." />
          </div>
          {model.description ? <p className="mt-1 line-clamp-2 text-xs text-muted-foreground">{model.description}</p> : null}
        </div>
        <dl className="flex flex-wrap gap-x-6 gap-y-1 text-xs">
          <div>
            <dt className="text-muted-foreground">Rows in table</dt>
            <dd className="font-medium tabular">{formatNumber(model.row_count)}</dd>
          </div>
          <div>
            <dt className="inline-flex items-center gap-1 text-muted-foreground">
              Sampled
              <HelpTip label="About sampling">Previews read a bounded sample of rows, never a full extract. Sorting and filtering apply to the sample.</HelpTip>
            </dt>
            <dd className="font-medium">{data ? <TimeAgo value={data.sampled_at} /> : '—'}</dd>
          </div>
        </dl>
        <Button asChild variant="outline" size="sm" className="self-start md:self-center">
          <Link to={wsPath(workspaceId, 'models', model.id)}>
            Open in catalog
            <ArrowUpRight aria-hidden />
          </Link>
        </Button>
      </section>

      <TableToolbar className="mb-0">
        <SearchInput value={search} onChange={setSearch} placeholder="Filter sample rows" className="sm:w-72" />
        <div className="flex items-center gap-2 sm:ml-auto">
          <ColumnMenu columns={data?.columns ?? []} hidden={hidden} onChange={setHidden} />
          <Select
            value={String(pageSize)}
            onValueChange={(v) => {
              setPageSize(Number(v))
              setPage(1)
            }}
          >
            <SelectTrigger size="sm" className="w-[7.5rem]" aria-label="Rows per page">
              <SelectValue />
            </SelectTrigger>
            <SelectContent>
              {PAGE_SIZES.map((n) => (
                <SelectItem key={n} value={String(n)}>
                  {n} rows
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>
      </TableToolbar>

      <p className="sr-only" aria-live="polite">
        {preview.isFetching ? 'Loading rows' : data ? `Showing ${data.rows.length} rows, page ${page}${total !== null ? ` of ${Math.max(1, Math.ceil(total / pageSize))}` : ''}.` : ''}
      </p>

      {preview.isLoading ? (
        <TableSkeleton rows={8} columns={6} />
      ) : preview.error && !data ? (
        <ErrorState error={preview.error} title={`Could not load rows from ${qualified}`} onRetry={() => void preview.refetch()} />
      ) : data && !data.columns.length ? (
        <EmptyState compact title="No columns" description="This table has no column definitions in the catalog yet, so there is nothing to preview." />
      ) : data && !data.rows.length ? (
        <EmptyState
          compact
          icon={SearchX}
          title={q ? 'No rows match this filter' : 'This table is empty'}
          description={q ? `No sampled row contains "${q}".` : 'The sample returned no rows. Run the pipeline that loads this table and try again.'}
          action={
            q ? (
              <Button variant="outline" size="sm" onClick={() => setSearch('')}>
                Clear filter
              </Button>
            ) : undefined
          }
        />
      ) : data ? (
        <div className="space-y-2">
          {preview.error ? <ErrorState compact error={preview.error} title="Could not refresh rows" onRetry={() => void preview.refetch()} /> : null}
          <PreviewGrid
            columns={columns}
            rows={data.rows}
            sort={sort}
            onSort={toggleSort}
            rowOffset={(page - 1) * pageSize}
            busy={preview.isPlaceholderData || preview.isFetching}
            label={`Sample rows from ${qualified}`}
          />
          {total !== null ? (
            <div className="rounded-lg border border-border">
              <Pagination page={page} totalPages={Math.max(1, Math.ceil(total / pageSize))} total={total} pageSize={pageSize} onPageChange={setPage} />
            </div>
          ) : (
            <div className="flex items-center justify-end gap-1 text-xs text-muted-foreground">
              <Button variant="ghost" size="icon-sm" onClick={() => setPage(page - 1)} disabled={page <= 1} aria-label="Previous page">
                <ChevronLeft className="size-4" />
              </Button>
              <span className="tabular">Page {page}</span>
              <Button variant="ghost" size="icon-sm" onClick={() => setPage(page + 1)} disabled={!hasNext} aria-label="Next page">
                <ChevronRight className="size-4" />
              </Button>
            </div>
          )}
          {total !== null ? (
            <p className="text-xs text-muted-foreground">
              Sample of {formatNumber(total)} row{total === 1 ? '' : 's'}
              {model.row_count !== null && model.row_count > total ? ` from ${formatNumber(model.row_count)} in the table` : ''}. Sorting and filtering
              apply to the sample only.
            </p>
          ) : null}
        </div>
      ) : null}
    </div>
  )
}
