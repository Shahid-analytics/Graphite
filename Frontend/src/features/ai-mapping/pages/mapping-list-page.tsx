import { Plus, Sparkles } from 'lucide-react'
import { useMemo, useState } from 'react'
import { Link, useNavigate } from 'react-router'
import { StatTile, TimeAgo } from '@/components/data/display'
import { EmptyState, ErrorState, TableSkeleton } from '@/components/feedback/states'
import { PageHeader, Section } from '@/components/layout/page-header'
import { SimulatedBadge } from '@/components/status/simulated'
import { LayerBadge } from '@/components/status/status-badge'
import { DataTable, FilterSelect, SearchInput, TableToolbar, type Column } from '@/components/tables/data-table'
import { Button } from '@/components/ui/button'
import { Progress } from '@/components/ui/progress'
import { usePermission, useWorkspace, wsPath } from '@/hooks/use-workspace'
import { isMockMode } from '@/lib/config'
import type { MappingSuggestionSetSummary } from '@/types'
import { DisabledReason } from '../components/disabled-reason'
import { ProviderNotice, providerReady } from '../components/provider-notice'
import { MappingStatusBadge } from '../components/status-badges'
import { WorkflowSteps } from '../components/workflow-steps'
import { STATUS_OPTIONS } from '../lib/labels'
import { useAiProviderStatus, useMappingSets } from '../queries'

const NO_PERMISSION = 'Your role does not include the mappings:review permission needed to request suggestions.'
const NO_PROVIDER = 'No AI provider is configured or enabled for this workspace. Configure one in Settings > AI provider.'

function NewSuggestionsButton({ workspaceId }: { workspaceId: string }) {
  const canReview = usePermission('mappings:review')
  const provider = useAiProviderStatus(workspaceId)
  // In live mode suggestions need a configured provider; the mock engine needs none.
  const reason = !canReview ? NO_PERMISSION : !isMockMode && provider.isSuccess && !providerReady(provider.data) ? NO_PROVIDER : null
  if (reason) {
    return (
      <DisabledReason reason={reason}>
        <Button disabled>
          <Plus aria-hidden />
          New suggestions
        </Button>
      </DisabledReason>
    )
  }
  return (
    <Button asChild>
      <Link to={wsPath(workspaceId, 'transformations', 'mapping', 'new')}>
        <Plus aria-hidden />
        New suggestions
      </Link>
    </Button>
  )
}

export default function MappingListPage() {
  const { workspaceId } = useWorkspace()
  const navigate = useNavigate()
  const query = useMappingSets(workspaceId)
  const [q, setQ] = useState('')
  const [status, setStatus] = useState('all')

  const sets = useMemo(() => query.data ?? [], [query.data])
  const rows = useMemo(() => {
    const needle = q.trim().toLowerCase()
    return sets.filter(
      (s) =>
        (status === 'all' || s.status === status) &&
        (!needle || [s.source_name, s.created_by.name, ...s.source_tables].some((v) => v.toLowerCase().includes(needle))),
    )
  }, [sets, q, status])

  const columns: Column<MappingSuggestionSetSummary>[] = [
    {
      id: 'source',
      header: 'Source',
      sortValue: (s) => s.source_name,
      cell: (s) => (
        <div className="min-w-0">
          <Link
            to={wsPath(workspaceId, 'transformations', 'mapping', s.id)}
            className="font-medium hover:underline"
            onClick={(e) => e.stopPropagation()}
          >
            {s.source_name}
          </Link>
          <p className="truncate font-mono text-[11.5px] text-muted-foreground md:hidden">{s.source_tables.join(', ')}</p>
        </div>
      ),
    },
    {
      id: 'tables',
      header: 'Tables',
      hideOnMobile: true,
      cell: (s) => (
        <div className="max-w-64">
          <p className="truncate font-mono text-[12px]" title={s.source_tables.join(', ')}>
            {s.source_tables.slice(0, 2).join(', ')}
          </p>
          {s.source_tables.length > 2 ? <p className="text-xs text-muted-foreground">+{s.source_tables.length - 2} more</p> : null}
        </div>
      ),
    },
    { id: 'layer', header: 'Target', sortValue: (s) => s.target_layer, cell: (s) => <LayerBadge layer={s.target_layer} /> },
    { id: 'status', header: 'Status', sortValue: (s) => s.status, cell: (s) => <MappingStatusBadge status={s.status} /> },
    {
      id: 'provider',
      header: 'Provider',
      hideOnMobile: true,
      cell: (s) => (
        <div className="flex flex-wrap items-center gap-1.5">
          <span className="text-xs text-muted-foreground">{s.provider.name}</span>
          {s.provider.simulated ? <SimulatedBadge always reason="Generated by the mock suggestion engine. No AI provider was called." /> : null}
        </div>
      ),
    },
    {
      id: 'progress',
      header: 'Decided',
      hideOnMobile: true,
      sortValue: (s) => (s.counts.total ? (s.counts.total - s.counts.pending) / s.counts.total : -1),
      cell: (s) =>
        s.status === 'generating' ? (
          <span className="text-xs text-subtle-foreground">Generating</span>
        ) : (
          <div className="w-28 space-y-1">
            <span className="text-xs tabular text-muted-foreground">
              {s.counts.total - s.counts.pending} / {s.counts.total}
            </span>
            <Progress value={s.counts.total ? ((s.counts.total - s.counts.pending) / s.counts.total) * 100 : 0} aria-label={`${s.counts.total - s.counts.pending} of ${s.counts.total} decided`} />
          </div>
        ),
    },
    {
      id: 'created',
      header: 'Created',
      sortValue: (s) => s.created_at,
      hideOnMobile: true,
      cell: (s) => (
        <div className="text-xs">
          <p>{s.created_by.name}</p>
          <TimeAgo value={s.created_at} className="text-muted-foreground" />
        </div>
      ),
    },
  ]

  const tally = (st: MappingSuggestionSetSummary['status']) => sets.filter((s) => s.status === st).length

  return (
    <div className="space-y-6">
      <PageHeader
        title="AI-assisted business mapping"
        breadcrumbs={[{ label: 'Transformations', to: wsPath(workspaceId, 'transformations') }, { label: 'AI mapping' }]}
        description="Suggest how Bronze source fields map to Silver and Gold models. Every suggestion is reviewed by a person and approved before it can become a schema change."
        actions={<NewSuggestionsButton workspaceId={workspaceId} />}
      />

      <ProviderNotice workspaceId={workspaceId} />

      <Section title="How the review works" description="Suggestions never change the warehouse on their own.">
        <WorkflowSteps />
      </Section>

      <Section title="Suggestion sets">
        {query.isPending ? (
          <TableSkeleton rows={4} columns={6} />
        ) : query.isError ? (
          <ErrorState error={query.error} title="Could not load mapping suggestions" onRetry={() => query.refetch()} />
        ) : !sets.length ? (
          <EmptyState
            icon={Sparkles}
            title="No mapping suggestions yet"
            description="Pick Bronze tables from a connected source and a target layer. You review every suggested field mapping, join, key and model before anything is approved."
            action={<NewSuggestionsButton workspaceId={workspaceId} />}
          />
        ) : (
          <div className="space-y-4">
            <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
              <StatTile label="Needs decisions" value={tally('ready')} hint="Reviewer decisions pending" />
              <StatTile label="Awaiting approval" value={tally('in_review')} hint="Submitted for review" />
              <StatTile label="Approved" value={tally('approved')} hint="Ready for a schema proposal" />
              <StatTile label="Rejected" value={tally('rejected')} />
            </div>
            <div>
              <TableToolbar>
                <SearchInput value={q} onChange={setQ} placeholder="Search source, tables or author" />
                <FilterSelect label="Statuses" value={status} onChange={setStatus} options={STATUS_OPTIONS} />
              </TableToolbar>
              <DataTable
                columns={columns}
                rows={rows}
                getRowId={(s) => s.id}
                onRowClick={(s) => navigate(wsPath(workspaceId, 'transformations', 'mapping', s.id))}
                initialSort={{ id: 'created', desc: true }}
                caption="Mapping suggestion sets"
              />
            </div>
          </div>
        )}
      </Section>
    </div>
  )
}
