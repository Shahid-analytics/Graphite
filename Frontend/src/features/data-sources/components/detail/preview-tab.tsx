import { RefreshCw, TableProperties } from 'lucide-react'
import { useState } from 'react'
import { HelpTip, TimeAgo } from '@/components/data/display'
import { EmptyState, ErrorState, TableSkeleton } from '@/components/feedback/states'
import { DataTable, type Column } from '@/components/tables/data-table'
import { SimulatedBadge } from '@/components/status/simulated'
import { Label } from '@/components/ui/label'
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select'
import { isApiError } from '@/services/api-error'
import type { PreviewColumn, Source } from '@/types'
import { BRONZE_HELP } from '../../lib/labels'
import { useTablePreview } from '../../queries'
import { GatedButton } from '../primitives'

const PAGE_SIZE = 25

type Row = Record<string, unknown> & { __row: number }

function CellValue({ value, column }: { value: unknown; column: PreviewColumn }) {
  if (value === null || value === undefined) return <span className="font-mono text-xs text-subtle-foreground">null</span>
  if (typeof value === 'boolean') return <span className="font-mono text-xs">{String(value)}</span>
  if (typeof value === 'number') return <span className="tabular">{value.toLocaleString('en')}</span>
  const text = String(value)
  const mono = /varchar|text|char/.test(column.data_type) && /^[A-Z]{2,4}-\d+$/.test(text)
  return (
    <span className={mono ? 'font-mono text-xs' : undefined} title={text.length > 40 ? text : undefined}>
      {text.length > 40 ? `${text.slice(0, 40)}…` : text}
    </span>
  )
}

export function PreviewTab({ source, syncReason, onSync }: { source: Source; syncReason: string | null; onSync: () => void }) {
  const options = source.selected_tables.map((t) => `${t.schema}.${t.name}`)
  const [chosen, setTable] = useState<string | null>(options[0] ?? null)
  // Fall back to the first table when the chosen one is removed from the selection.
  const table = chosen && options.includes(chosen) ? chosen : (options[0] ?? null)
  const [page, setPage] = useState(1)
  const { data, isLoading, isFetching, error, refetch } = useTablePreview(source.id, table, page, PAGE_SIZE)

  if (!options.length) {
    return <EmptyState icon={TableProperties} title="No tables selected" description="Select tables on the Tables tab, sync them, then preview sample rows here." />
  }

  const noData = isApiError(error) && error.code === 'no_data_loaded'
  const columns: Column<Row>[] = (data?.columns ?? []).map((column) => ({
    id: column.name,
    header: (
      <span className="flex flex-col normal-case">
        <span className="font-mono text-[12px] text-foreground">{column.name}</span>
        <span className="text-[11px] font-normal text-subtle-foreground">{column.data_type}</span>
      </span>
    ),
    className: 'whitespace-nowrap',
    cell: (row) => <CellValue value={row[column.name]} column={column} />,
  }))
  const rows: Row[] = (data?.rows ?? []).map((row, i) => ({ ...row, __row: (page - 1) * PAGE_SIZE + i }))

  return (
    <div className="space-y-3">
      <div className="flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between">
        <div className="grid gap-1.5">
          <Label htmlFor="preview-table">Table</Label>
          <Select
            value={table ?? undefined}
            onValueChange={(v) => {
              setTable(v)
              setPage(1)
            }}
          >
            <SelectTrigger id="preview-table" className="w-full font-mono text-[13px] sm:w-72">
              <SelectValue placeholder="Choose a table" />
            </SelectTrigger>
            <SelectContent>
              {options.map((o) => (
                <SelectItem key={o} value={o}>
                  <span className="font-mono text-[13px]">{o}</span>
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>
        <div className="flex flex-wrap items-center gap-2 text-xs text-muted-foreground">
          <span className="inline-flex items-center gap-1">
            Sample of the Bronze copy, at most 100 rows
            <HelpTip label="About this preview">
              {BRONZE_HELP} The preview reads a bounded sample from the last successful load; it never extracts the full table.
            </HelpTip>
          </span>
          {data ? (
            <span>
              Loaded <TimeAgo value={data.sampled_at} />
            </span>
          ) : null}
          <SimulatedBadge label="Simulated rows" reason="Rows are generated by the in-browser mock API to resemble the table. They are not real customer data." />
        </div>
      </div>

      {isLoading ? (
        <TableSkeleton columns={6} rows={8} />
      ) : noData ? (
        <EmptyState
          icon={TableProperties}
          title="No data loaded yet"
          description="This source has not completed a successful sync, so Bronze has nothing to sample. Run a sync, then come back."
          action={
            <GatedButton reason={syncReason} onClick={onSync}>
              <RefreshCw className="size-4" aria-hidden />
              Sync now
            </GatedButton>
          }
        />
      ) : error ? (
        <ErrorState error={error} title="Could not load the preview" onRetry={() => void refetch()} />
      ) : data && rows.length ? (
        <div aria-busy={isFetching}>
          <DataTable
            columns={columns}
            rows={rows}
            getRowId={(r) => String(r.__row)}
            caption={`Sample rows from ${table}`}
            pagination={{ page: data.page, pageSize: data.page_size, total: data.total_rows ?? rows.length, onPageChange: setPage }}
          />
        </div>
      ) : (
        <EmptyState compact icon={TableProperties} title="The table is empty" description="The last sync loaded no rows for this table." />
      )}
    </div>
  )
}
