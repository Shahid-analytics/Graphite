import { ArrowUpRight, History } from 'lucide-react'
import { useState } from 'react'
import { Link, useNavigate } from 'react-router'
import { TimeAgo } from '@/components/data/display'
import { EmptyState, ErrorState, TableSkeleton } from '@/components/feedback/states'
import { DataTable, FilterSelect, TableToolbar, type Column } from '@/components/tables/data-table'
import { RunStatusBadge } from '@/components/status/status-badge'
import { SimulatedBadge } from '@/components/status/simulated'
import { Button } from '@/components/ui/button'
import { useWorkspace, wsPath } from '@/hooks/use-workspace'
import { formatDuration, formatNumber } from '@/lib/format'
import type { Run, RunKind, RunStatus } from '@/types'
import { useSourceRuns } from '../../queries'
import { runLabel, RunRowAction, TRIGGER_LABELS } from './run-helpers'

const PAGE_SIZE = 15

const STATUS_FILTERS: { value: RunStatus; label: string }[] = [
  { value: 'running', label: 'Running' },
  { value: 'queued', label: 'Queued' },
  { value: 'succeeded', label: 'Succeeded' },
  { value: 'failed', label: 'Failed' },
  { value: 'cancelled', label: 'Cancelled' },
]

const KIND_FILTERS: { value: RunKind; label: string }[] = [
  { value: 'ingestion', label: 'Source syncs' },
  { value: 'pipeline', label: 'Pipeline runs' },
]

export function RunsTab({ sourceId, onRunStarted }: { sourceId: string; onRunStarted: (run: Run) => void }) {
  const { workspaceId } = useWorkspace()
  const navigate = useNavigate()
  const [status, setStatus] = useState('all')
  const [kind, setKind] = useState('all')
  const [page, setPage] = useState(1)
  const query = {
    page,
    page_size: PAGE_SIZE,
    status: status === 'all' ? undefined : (status as RunStatus),
    kind: kind === 'all' ? undefined : (kind as RunKind),
  }
  const { data, isLoading, error, refetch } = useSourceRuns(sourceId, query)

  const columns: Column<Run>[] = [
    { id: 'status', header: 'Status', cell: (r) => <RunStatusBadge status={r.status} /> },
    {
      id: 'run',
      header: 'Run',
      cell: (r) => (
        <div className="min-w-0">
          <Link to={wsPath(workspaceId, 'runs', r.id)} className="block truncate font-medium hover:underline" onClick={(e) => e.stopPropagation()}>
            {runLabel(r)}
          </Link>
          <p className="truncate text-xs text-muted-foreground">
            {TRIGGER_LABELS[r.trigger]} by {r.triggered_by.name}
            {r.attempt > 1 ? ` · attempt ${r.attempt}` : ''}
          </p>
        </div>
      ),
    },
    { id: 'started', header: 'Started', cell: (r) => <TimeAgo value={r.started_at ?? r.queued_at} /> },
    { id: 'duration', header: 'Duration', hideOnMobile: true, className: 'tabular', cell: (r) => formatDuration(r.duration_seconds) },
    { id: 'records', header: 'Records', hideOnMobile: true, className: 'tabular', cell: (r) => formatNumber(r.records_processed) },
    {
      id: 'error',
      header: 'Error',
      hideOnMobile: true,
      className: 'max-w-72',
      cell: (r) =>
        r.error ? (
          <p className="truncate text-xs" title={r.error.message}>
            <span className="font-mono text-muted-foreground">{r.error.code}</span> {r.error.message}
          </p>
        ) : (
          <span className="text-subtle-foreground">—</span>
        ),
    },
    {
      id: 'actions',
      header: <span className="sr-only">Actions</span>,
      className: 'text-right whitespace-nowrap',
      cell: (r) => (
        <div className="flex items-center justify-end gap-1">
          <RunRowAction run={r} onRetried={onRunStarted} />
          <Button asChild variant="ghost" size="icon-sm" aria-label={`Open run ${r.id}`}>
            <Link to={wsPath(workspaceId, 'runs', r.id)} onClick={(e) => e.stopPropagation()}>
              <ArrowUpRight className="size-4" aria-hidden />
            </Link>
          </Button>
        </div>
      ),
    },
  ]

  const filtering = status !== 'all' || kind !== 'all'

  return (
    <div>
      <TableToolbar>
        <FilterSelect
          value={status}
          onChange={(v) => {
            setStatus(v)
            setPage(1)
          }}
          options={STATUS_FILTERS}
          label="Statuses"
        />
        <FilterSelect
          value={kind}
          onChange={(v) => {
            setKind(v)
            setPage(1)
          }}
          options={KIND_FILTERS}
          label="Run types"
        />
        <SimulatedBadge className="sm:ml-auto" label="Simulated history" reason="Run history is generated by the in-browser mock API. No real pipeline ran." />
      </TableToolbar>
      {isLoading ? (
        <TableSkeleton columns={6} />
      ) : error ? (
        <ErrorState error={error} title="Could not load runs" onRetry={() => void refetch()} />
      ) : (
        <DataTable
          columns={columns}
          rows={data?.items ?? []}
          getRowId={(r) => r.id}
          onRowClick={(r) => navigate(wsPath(workspaceId, 'runs', r.id))}
          pagination={data ? { page: data.page, pageSize: data.page_size, total: data.total, onPageChange: setPage } : undefined}
          caption="Runs for this source"
          empty={
            <EmptyState
              compact
              icon={History}
              title={filtering ? 'No runs match these filters' : 'No runs yet'}
              description={filtering ? 'Try another status or run type.' : 'Run a sync to load this source into Bronze.'}
              action={
                filtering ? (
                  <Button
                    variant="outline"
                    size="sm"
                    onClick={() => {
                      setStatus('all')
                      setKind('all')
                      setPage(1)
                    }}
                  >
                    Clear filters
                  </Button>
                ) : undefined
              }
            />
          }
        />
      )}
    </div>
  )
}
