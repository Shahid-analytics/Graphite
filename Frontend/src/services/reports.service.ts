import type {
  AnalyticsListQuery,
  CreateReportRequest,
  CreateReportRequestRequest,
  Dashboard,
  EmbedSession,
  MetabaseStatus,
  Report,
  ReportRequest,
  ReportSuggestion,
  ReportSuggestionRequest,
} from '@/types'
import { api } from './api-client'

export const reportsService = {
  dashboards: (workspaceId: string, query: AnalyticsListQuery = {}) =>
    api.get<Dashboard[]>(`/workspaces/${workspaceId}/dashboards`, { query }),
  dashboard: (dashboardId: string) => api.get<Dashboard>(`/dashboards/${dashboardId}`),
  favoriteDashboard: (dashboardId: string, isFavorite: boolean) =>
    api.post<Dashboard>(`/dashboards/${dashboardId}/favorite`, { is_favorite: isFavorite }),
  /** Requests a signed, short-lived Metabase embed URL generated by the backend. */
  embedSession: (dashboardId: string) => api.post<EmbedSession>(`/dashboards/${dashboardId}/embed-session`),

  reports: (workspaceId: string, query: AnalyticsListQuery = {}) => api.get<Report[]>(`/workspaces/${workspaceId}/reports`, { query }),
  report: (reportId: string) => api.get<Report>(`/reports/${reportId}`),
  createReport: (workspaceId: string, payload: CreateReportRequest) => api.post<Report>(`/workspaces/${workspaceId}/reports`, payload),
  favoriteReport: (reportId: string, isFavorite: boolean) =>
    api.post<Report>(`/reports/${reportId}/favorite`, { is_favorite: isFavorite }),
  /** Publishes a reviewed draft to Metabase. Fails with 409 when Metabase is not connected. */
  publishReport: (reportId: string) => api.post<Report>(`/reports/${reportId}/publish`),

  suggest: (payload: ReportSuggestionRequest) => api.post<ReportSuggestion>('/ai/report-suggestions', payload),

  reportRequests: (workspaceId: string) => api.get<ReportRequest[]>(`/workspaces/${workspaceId}/report-requests`),
  createReportRequest: (workspaceId: string, payload: CreateReportRequestRequest) =>
    api.post<ReportRequest>(`/workspaces/${workspaceId}/report-requests`, payload),

  metabaseStatus: (workspaceId: string) =>
    api.get<MetabaseStatus>('/integrations/metabase/status', { query: { workspace_id: workspaceId } }),
  testMetabase: (workspaceId: string) =>
    api.post<MetabaseStatus>('/integrations/metabase/test-connection', { workspace_id: workspaceId }),
}
